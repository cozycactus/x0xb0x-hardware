    d.route((60.96, 71.12), (50.8, 71.12))
    d.label('DINSYNC3', (50.8, 71.12), 'L')
    d.across('R24', 132.08, 50.8, '2')
    d.route('DIN4.1', (119.38, 55.88), (119.38, 50.8), 'R24.2')
    d.down('R25', 142.24, 58.42, '2')
    d.route('R24.1', (142.24, 50.8), 'R25.2')
    d.ground('R25.1')
    d.route((142.24, 50.8), (149.86, 50.8))
    d.label('DINSYNC1', (149.86, 50.8), 'R')
    d.across('R23', 132.08, 71.12, '1')
    d.route('DIN4.4', (114.3, 71.12), 'R23.1')
