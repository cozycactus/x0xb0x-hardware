    d.label('DINSYNC2', (149.86, 71.12), 'R')
    d.across('R20', 129.54, 60.96, '1')
    d.route('DIN4.2', 'R20.1')
    d.ground('R20.2', 'R')

    # MIDI thru.
    d.caption('MIDI THRU', 40.64, 96.52)
    d.chip('DIN2', DIN, 1, 101.6, 104.14, ref_at=(101.6, 91.44), val_at=(101.6, 118.0))
