    d.route('DIN4.3', (83.82, 55.88), (83.82, 50.8), 'R21.1')
    d.down('R28', 60.96, 58.42, '2')
    d.route('R21.2', (60.96, 50.8), 'R28.2')
    d.ground('R28.1')
    d.route((60.96, 50.8), (50.8, 50.8))
    d.label('DINSYNC4', (50.8, 50.8), 'L')
