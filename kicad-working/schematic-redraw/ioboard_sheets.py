def draw_usb(d):
    d.dx, d.dy = 25.4, 25.4
    d.block('USB', 20.32, 33.02, 270.0, 165.1)
    d.chip('USB0', "ACON_TYPEB''", 1, 60.96, 96.52, 180, ref_at=(50.8, 86.36), hide_value=True)
